W = IMG_W                      # slot maths use the printed image, not the framed board object
H = W / ASPECT


def world(u, v):
    return round(CX + (u - .5) * W + NUDGE_ALL[0], 2), round(CZ - (v - .5) * H + NUDGE_ALL[1], 2)


def S(name):
    x, z = world(*SLOT_UV[name])
    dx, dz = NUDGE.get(name, (0, 0))
    return round(x + dx, 2), round(z + dz, 2)


def lit(x, z, y=2):
    f = lambda n: ('%g' % n)
    return '{%s,%s,%s}' % (f(x), f(y), f(z))


def slot_lit(name, y=2):
    return lit(*S(name), y=y)


CITYX = [world(u, CITY_V)[0] for u in reversed(CITY_U)]   # rightmost first, like the old i=1 slot
CITYZ = world(CITY_U[0], CITY_V)[1]
HQX = [world(u, HQ_V)[0] for u in reversed(CITY_U)]
HQZ = world(CITY_U[0], HQ_V)[1]
STAGE_X = S('mastermind')[0]


def header():
    fx = lambda a: '{' + ','.join('%g' % v for v in a) + '}'
    vx, vz = S('villains')
    slots = ', '.join('%s = {x = %g, z = %g}' % ((k,) + S(k)) for k in sorted(SLOT_UV))
    slots += ', mm2 = {x = %g, z = %g}' % (S('scheme')[0], STAGE_Z)          # second Mastermind of a scenario: above the Scheme slot
    return (
        '--[[ Universal Mat layout: slot tables generated by the save builder --]]\n'
        'SLOTS = {%s}\n'
        'CITYX = %s\nCITYZ = %g\nHQX = %s\nHQZ = %g\n'
        'function _fragPos(i)\n'
        '    if i == 1 then return {%g,2,%g} end\n'
        '    return {CITYX[i-1],2,CITYZ}\n'
        'end\n\n') % (slots, fx(CITYX), CITYZ, fx(HQX), HQZ, vx, vz)


def _rep(src, old, new, count, report, label=None):
    n = src.count(old)
    if n != count:
        raise SystemExit('PATCH FAILED: %r expected %d occurrence(s), found %d' % (old, count, n))
    report.append('%-34s x%d -> %s' % (label or old, n, new if len(new) < 60 else new[:57] + '...'))
    return src.replace(old, new)


