def patch_bag(src):
    """Expansion-bag scripts run in their own environment (no Global variables): literals only."""
    sx, sz = S('sidekick'); ax, az = S('adversaries'); hx, hz = S('horrors'); bx, bz = S('bindings')
    table = [
        ('{12.75,2,14}', lit(12.75, STAGE_Z)),
        ('{-9.75,2,1}', lit(sx, sz)),
        ('{-4.75,2,20}', lit(bx, bz)),               # Ambitions (Secret Wars 1): the Bindings slot, not the Escaped box
        ('{-1,2,20}', lit(bx, bz, y=3.5)),           # Ambitions (Secret Wars 2): on top of the first
        ('{-2.5,2,20}', lit(hx, hz)),
    ]
    counts = {}
    for old, new in table:
        counts[old] = src.count(old)
        src = src.replace(old, new)
    return src, counts


def describe():
    out = ['board centre (%g, %g)  printed image %.2f x %.2f  (object width incl. frame %.1f)' % (CX, CZ, W, H, BOUNDS_W),
           'board extent x %.2f..%.2f  z %.2f..%.2f' % (CX - W / 2, CX + W / 2, CZ - H / 2, CZ + H / 2)]
    for k in SLOT_UV: out.append('  %-12s %s' % (k, S(k)))
    out.append('  CITYX (rightmost first) %s  z %g' % (CITYX, CITYZ))
    out.append('  HQX   (rightmost first) %s  z %g' % (HQX, HQZ))
    return '\n'.join(out)


